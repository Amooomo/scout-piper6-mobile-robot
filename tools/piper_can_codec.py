@dataclass(frozen=True)
class CanFrame:
    """One received CAN frame (timestamp supplied by the reader)."""

    timestamp_s: float
    arbitration_id: int
    data: bytes


@dataclass(frozen=True)
class PiperStatus:
    ctrl_mode: int
    arm_status: int
    mode_feedback: int
    teach_status: int
    motion_status: int
    trajectory_num: int
    joint_limit_error_bits: int
    joint_comm_error_bits: int
    raw: tuple[int, ...]

    @property
    def arm_status_name(self) -> str:
        return STATUS_ARM_NAMES.get(self.arm_status, f"UNKNOWN_0x{self.arm_status:02X}")

    @property
    def ctrl_mode_name(self) -> str:
        return STATUS_CTRL_MODE_NAMES.get(self.ctrl_mode, f"UNKNOWN_0x{self.ctrl_mode:02X}")

    @property
    def mode_name(self) -> str:
        return STATUS_MODE_NAMES.get(self.mode_feedback, f"UNKNOWN_0x{self.mode_feedback:02X}")

    @property
    def motion_name(self) -> str:
        return STATUS_MOTION_NAMES.get(self.motion_status, f"UNKNOWN_0x{self.motion_status:02X}")

    @property
    def error_code(self) -> int:
        """Raw two-byte fault bitmap: low byte joint-limit, high byte comm."""
        return (self.raw[7] << 8) | self.raw[6]

    def as_dict(self) -> dict[str, Any]:
        return {
            "ctrl_mode": self.ctrl_mode,
            "ctrl_mode_name": self.ctrl_mode_name,
            "arm_status": self.arm_status,
            "arm_status_name": self.arm_status_name,
            "mode_feedback": self.mode_feedback,
            "mode_name": self.mode_name,
            "teach_status": self.teach_status,
            "motion_status": self.motion_status,
            "motion_name": self.motion_name,
            "trajectory_num": self.trajectory_num,
            "error_code": self.error_code,
            "error_code_hex": f"0x{self.error_code:04X}",
            "joint_limit_error_bits": self.joint_limit_error_bits,
            "joint_comm_error_bits": self.joint_comm_error_bits,
            "raw": list(self.raw),
        }


@dataclass(frozen=True)
class GripperFrame:
    target_um: int
    effort_mnm: int
    status_code: int
    set_zero: int


# ---------------------------------------------------------------------------
# Low-level frame / value codecs
# ---------------------------------------------------------------------------


def parse_can_frame(raw: bytes) -> tuple[int, bytes]:
    """Parse a Linux ``struct can_frame`` into (arbitration_id, payload)."""
    if len(raw) < CAN_FRAME_STRUCT.size:
        raise ValueError(f"CAN frame needs >= {CAN_FRAME_STRUCT.size} bytes, got {len(raw)}")
    can_id, dlc, payload = CAN_FRAME_STRUCT.unpack(raw[: CAN_FRAME_STRUCT.size])
    if dlc > 8:
        raise ValueError(f"CAN DLC {dlc} exceeds 8")
    return can_id & CAN_EFF_MASK, payload[:dlc]


def encode_can_frame(arbitration_id: int, data: bytes) -> bytes:
    """Build a Linux ``struct can_frame``. Intended for tests/tools, not TX."""
    payload = bytes(data)
    if len(payload) > 8:
        raise ValueError(f"CAN payload must be <= 8 bytes, got {len(payload)}")
    return CAN_FRAME_STRUCT.pack(
        int(arbitration_id) & CAN_EFF_MASK,
        len(payload),
        payload.ljust(8, b"\x00"),
    )


def decode_joint_pair(data: bytes) -> tuple[int, int]:
    """Decode two joint values in millidegrees (big-endian signed int32)."""
    if len(data) < 8:
        raise ValueError(f"joint pair needs 8 bytes, got {len(data)}")
    return struct.unpack(">ii", data[:8])


def encode_joint_pair(first_mdeg: int, second_mdeg: int) -> bytes:
    return struct.pack(">ii", int(first_mdeg), int(second_mdeg))


def decode_gripper(data: bytes) -> int:
    """Decode gripper feedback in micrometres (big-endian signed int32)."""
    if len(data) < 4:
        raise ValueError(f"gripper feedback needs 4 bytes, got {len(data)}")
    return struct.unpack(">i", data[:4])[0]


def decode_gripper_frame(data: bytes) -> GripperFrame:
    if len(data) < 8:
        raise ValueError(f"gripper frame needs 8 bytes, got {len(data)}")
    target_um, effort_mnm, status_code, set_zero = struct.unpack(">iHBB", data[:8])
    return GripperFrame(target_um, effort_mnm, status_code, set_zero)


def encode_gripper_frame(
    target_um: int,
    effort_mnm: int,
    status_code: int = 0x01,
    set_zero: int = 0x00,
) -> bytes:
    target_um = max(0, int(target_um))
    effort_mnm = max(0, min(5000, int(effort_mnm)))
    return struct.pack(">iHBB", target_um, effort_mnm, status_code, set_zero)


def decode_status(data: bytes) -> PiperStatus:
    """Decode the 0x2A1 arm-status frame.

    Bytes 6/7 are two fault bitmaps (joint-angle-limit and joint-communication),
    each with bits 0..5 for J1..J6.
    """
    if len(data) < 8:
        raise ValueError(f"status frame needs 8 bytes, got {len(data)}")
    values = tuple(int(value) for value in data[:8])
    return PiperStatus(
        ctrl_mode=values[0],
        arm_status=values[1],
        mode_feedback=values[2],
        teach_status=values[3],
        motion_status=values[4],
        trajectory_num=values[5],
        joint_limit_error_bits=values[6] & 0x3F,
        joint_comm_error_bits=values[7] & 0x3F,
        raw=values,
    )


