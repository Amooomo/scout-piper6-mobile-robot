@dataclass
class PiperFeedback:
    """Accumulate the five follower feedback frames into one snapshot."""

    joints_mdeg: list[int | None] = field(default_factory=lambda: [None] * 6)
    gripper_um: int | None = None
    status: PiperStatus | None = None
    counts: dict[int, int] = field(default_factory=dict)
    malformed: int = 0

    def update(self, arbitration_id: int, data: bytes) -> bool:
        """Apply one frame; return True if it is a recognised feedback frame."""
        can_id = int(arbitration_id)
        if can_id == ID_JOINT_FEEDBACK_12:
            first, second = decode_joint_pair(data)
            self.joints_mdeg[0:2] = [first, second]
        elif can_id == ID_JOINT_FEEDBACK_34:
            first, second = decode_joint_pair(data)
            self.joints_mdeg[2:4] = [first, second]
        elif can_id == ID_JOINT_FEEDBACK_56:
            first, second = decode_joint_pair(data)
            self.joints_mdeg[4:6] = [first, second]
        elif can_id == ID_GRIPPER_FEEDBACK:
            self.gripper_um = decode_gripper(data)
        elif can_id == ID_STATUS_FEEDBACK:
            self.status = decode_status(data)
        else:
            return False
        self.counts[can_id] = self.counts.get(can_id, 0) + 1
        return True

    @property
    def joints_deg(self) -> list[float | None]:
        return [None if value is None else value / 1000.0 for value in self.joints_mdeg]

    @property
    def gripper_mm(self) -> float | None:
        return None if self.gripper_um is None else self.gripper_um / 1000.0

    @property
    def complete(self) -> bool:
        return all(value is not None for value in self.joints_mdeg) and self.gripper_um is not None

    def state_vector(self) -> list[float] | None:
        """[J1..J6 deg, gripper mm], or None when any field is missing."""
        joints = self.joints_deg
        gripper = self.gripper_mm
        if any(value is None for value in joints) or gripper is None:
            return None
        return [float(value) for value in joints] + [float(gripper)]


def decode_feedback_frames(frames: Sequence[CanFrame]) -> PiperFeedback:
    """Decode an iterable of frames, counting malformed feedback payloads."""
    feedback = PiperFeedback()
    for frame in frames:
        try:
            feedback.update(frame.arbitration_id, frame.data)
        except (ValueError, struct.error):
            feedback.malformed += 1
    return feedback


def nominal_limit_report(joints_deg: Sequence[float | None]) -> dict[str, Any]:
    """Report nominal range / margin for supplied joint angles."""
    if len(joints_deg) < 6:
        raise ValueError(f"need at least 6 joints, got {len(joints_deg)}")
    report: dict[str, Any] = {}
    for index, name in enumerate(JOINT_NAMES):
        value = joints_deg[index]
        low, high = JOINT_LIMITS_DEG[index]
        entry: dict[str, Any] = {"range_deg": [low, high], "current_deg": value, "inside": None}
        if value is not None:
            entry.update(
                {
                    "inside": bool(low <= value <= high),
                    "margin_low_deg": float(value - low),
                    "margin_high_deg": float(high - value),
                    "limit_margin_deg": float(min(value - low, high - value)),
                }
            )
        report[name] = entry
    return report
